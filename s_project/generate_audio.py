async def generate_voiceovers():
    out_dir = r"C:\Users\master\vet_animal_hospital\s_project\audio"
    os.makedirs(out_dir, exist_ok=True)
    voice = "ko-KR-InJoonNeural"
    
    for scene in SCENES:
        sid = scene["id"]
        out_path = os.path.join(out_dir, f"{sid}.mp3")
        print(f"Generating voiceover for {sid}...")
        comm = edge_tts.Communicate(scene["script"], voice, rate="-2%")
        await comm.save(out_path)
        print(f"Saved: {out_path}")

if __name__ == "__main__":
    asyncio.run(generate_voiceovers())
